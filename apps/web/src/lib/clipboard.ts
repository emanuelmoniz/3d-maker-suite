/**
 * Copies text to the clipboard. `navigator.clipboard` exists only in a secure context, and a hub
 * opened at http://<lan-ip> isn't one, so this falls back to a hidden textarea and execCommand.
 * Resolves to false when neither works (the caller then asks the user to copy by hand).
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // Denied or unavailable: try the fallback below.
  }
  const area = document.createElement("textarea");
  area.value = text;
  area.setAttribute("readonly", "");
  area.style.position = "fixed";
  area.style.top = "0";
  area.style.opacity = "0";
  document.body.appendChild(area);
  area.select();
  try {
    return document.execCommand("copy");
  } catch {
    return false;
  } finally {
    area.remove();
  }
}
